"""
Saved Keras Model Loader for DermaScan AI Inference API.
Never generates fake predictions when the trained model artifact is absent.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Any, Dict, Optional

import tensorflow as tf

ARTIFACTS_DIR = os.path.join(os.path.dirname(__file__), "artifacts")
DEFAULT_MODEL_PATH = os.path.join(ARTIFACTS_DIR, "dermascan_efficientnetb0.keras")
DEFAULT_METRICS_PATH = os.path.join(ARTIFACTS_DIR, "evaluation_metrics.json")


@dataclass
class ModelBundle:
    model: Optional[tf.keras.Model]
    model_path: str
    loaded: bool
    message: str


def load_trained_model(model_path: str = DEFAULT_MODEL_PATH) -> ModelBundle:
    """Loads the trained EfficientNetB0 Keras model if available on disk."""
    if not os.path.isfile(model_path):
        return ModelBundle(
            model=None,
            model_path=model_path,
            loaded=False,
            message=(
                f"Trained EfficientNetB0 model not found at '{model_path}'. "
                "Run `python train.py --data-dir /path/to/HAM10000` before running predictions."
            ),
        )

    try:
        model = tf.keras.models.load_model(model_path)
        return ModelBundle(
            model=model,
            model_path=model_path,
            loaded=True,
            message="EfficientNetB0 model loaded and ready for inference.",
        )
    except Exception as exc:
        return ModelBundle(
            model=None,
            model_path=model_path,
            loaded=False,
            message=f"Failed to load saved Keras model: {exc}",
        )


def load_evaluation_metrics(metrics_path: str = DEFAULT_METRICS_PATH) -> Optional[Dict[str, Any]]:
    """Loads persisted real evaluation metrics JSON generated by evaluate.py."""
    if not os.path.isfile(metrics_path):
        return None
    with open(metrics_path, "r", encoding="utf-8") as f:
        return json.load(f)
